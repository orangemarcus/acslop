export default function AchievementToast({ achievement, onDismiss }: AchievementToastProps) {
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    if (achievement) {
      setVisible(true);
      const timer = setTimeout(() => {
        setVisible(false);
        setTimeout(onDismiss, 300);
      }, 4000);
      return () => clearTimeout(timer);
    }
  }, [achievement, onDismiss]);

  if (!achievement) return null;

  return (
    <div
      className={`fixed bottom-6 right-6 z-50 transition-all duration-300 ${
        visible ? 'translate-y-0 opacity-100' : 'translate-y-4 opacity-0'
      }`}
    >
      <div className="bg-white dark:bg-warm-800 border border-cream-300 dark:border-warm-700 rounded-2xl shadow-lg p-4 flex items-center gap-3 min-w-[280px]">
        <div className="w-10 h-10 rounded-xl bg-cream-100 dark:bg-warm-700 flex items-center justify-center flex-shrink-0">
          <BadgeIcon icon={achievement.icon} color={achievement.color} />
        </div>
        <div className="flex-1 min-w-0">
          <p className="text-[10px] text-amber-600 dark:text-amber-400 font-bold uppercase tracking-wider">
            Achievement Unlocked!
          </p>
          <p className="text-sm font-semibold text-warm-900 dark:text-warm-100 truncate">
            {achievement.name}
          </p>
          <p className="text-[11px] text-warm-500 dark:text-warm-400 truncate">
            {achievement.description}
          </p>
        </div>
        <button
          onClick={() => { setVisible(false); setTimeout(onDismiss, 300); }}
          className="text-warm-400 hover:text-warm-600 dark:text-warm-500 dark:hover:text-warm-300 flex-shrink-0"
        >
          <svg className="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
          </svg>
        </button>
      </div>
    </div>
  );
}
